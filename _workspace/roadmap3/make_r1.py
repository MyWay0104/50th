def split_scene(html: str, sid: str) -> tuple[str, str] | None:
    """장면을 화면 부분과 노트 부분으로 나눈다."""
    m = re.search(rf'<section [^>]*data-scene-id="{re.escape(sid)}".*?</section>', html, re.S)
    if m is None:
        return None
    sc = m.group(0)
    cut = sc.find(NOTE_MARK)
    return (sc[:cut], sc[cut:]) if cut >= 0 else (sc, "")


def main() -> None:
    """항목을 장면별로 묶어 표를 만들고 원문 일치를 확인한다."""
    html = INDEX.read_text(encoding="utf-8")
    by_scene: dict[str, list[dict]] = {}
    problems: list[str] = []

    for sid, where, old, new, tag in ITEMS:
        parts = split_scene(html, sid)
        if parts is None:
            problems.append(f"{tag} {sid}: 장면을 찾지 못함")
            continue
        part = parts[0] if where == "screen" else parts[1]
        n = part.count(old)
        if n != 1:
            problems.append(f"{tag} {sid} {where} {n}회: {old[:60]}")
            continue
        by_scene.setdefault(sid, []).append({"where": where, "old": old, "new": new})

    if problems:
        log.info("원문이 맞지 않는 항목 %d개 — 저장하지 않았다", len(problems))
        for p in problems:
            log.info("  %s", p)
        return

    # 장면 순서를 index.html 등장 순서에 맞춘다
    order = {m.group(1): i for i, m in enumerate(re.finditer(r'data-scene-id="([^"]+)"', html))}
    lines = [
        json.dumps({"sid": sid, "replace": rules}, ensure_ascii=False)
        for sid, rules in sorted(by_scene.items(), key=lambda kv: order.get(kv[0], 999))
    ]
